// Package setup creates a runnable GoMTA configuration from scratch.
package setup

import (
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/ferchd/gomta/internal/auth"
	"github.com/ferchd/gomta/internal/dkimkey"
	"github.com/ferchd/gomta/internal/tlsutil"
	"github.com/ferchd/gomta/plugin"
)

// Options configures Init.
type Options struct {
	Dir           string
	Hostname      string
	Domains       []string
	AdminUser     string
	AdminPassword string
	Selector      string
	KeyBits       int
	Force         bool
}

// Result reports what Init created.
type Result struct {
	Dir               string
	ConfigPath        string
	Hostname          string
	Domains           []string
	AdminUser         string
	Password          string
	PasswordGenerated bool
	Selector          string
	KeyFile           string
	DNSRecords        []DNSRecord
	GeneratedFiles    []string
}

// DNSRecord is one suggested DNS entry.
type DNSRecord struct {
	Name  string
	Type  string
	Value string
	Note  string
}

// Init writes configuration, policy files, TLS material, and a DKIM key.
func Init(opts Options) (*Result, error) {
	dir := strings.TrimSpace(opts.Dir)
	if dir == "" {
		dir = "."
	}
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	hostname := strings.TrimSpace(opts.Hostname)
	if hostname == "" {
		hostname, _ = os.Hostname()
	}
	if hostname == "" {
		return nil, fmt.Errorf("hostname is required")
	}
	domains := normalizeDomains(opts.Domains)
	if len(domains) == 0 {
		return nil, fmt.Errorf("at least one domain is required (use -domain example.com)")
	}
	for _, domain := range domains {
		if !plugin.ValidAddress("postmaster@"+domain, false) {
			return nil, fmt.Errorf("invalid domain %q", domain)
		}
	}
	selector := strings.TrimSpace(opts.Selector)
	if selector == "" {
		selector = "default"
	}
	keyBits := opts.KeyBits
	if keyBits <= 0 {
		keyBits = 2048
	}

	adminUser := strings.ToLower(strings.TrimSpace(opts.AdminUser))
	if adminUser == "" {
		adminUser = "postmaster@" + domains[0]
	}
	if !strings.Contains(adminUser, "@") {
		adminUser += "@" + domains[0]
	}
	password := opts.AdminPassword
	generated := false
	if password == "" {
		password, err = randomPassword()
		if err != nil {
			return nil, err
		}
		generated = true
	}
	hash, err := auth.HashPassword(password)
	if err != nil {
		return nil, err
	}

	configPath := filepath.Join(abs, "gomta.yaml")
	pluginsPath := filepath.Join(abs, "plugins.yaml")
	domainsPath := filepath.Join(abs, "domains.txt")
	usersPath := filepath.Join(abs, "users.txt")
	certPath := filepath.Join(abs, "tls", "cert.pem")
	keyPath := filepath.Join(abs, "tls", "key.pem")
	dkimDir := filepath.Join(abs, "dkim")
	dkimPath := filepath.Join(dkimDir, selector+".key")

	files := []string{configPath, pluginsPath, domainsPath, usersPath}
	if !opts.Force {
		var existing []string
		for _, path := range files {
			if _, err := os.Stat(path); err == nil {
				existing = append(existing, path)
			}
		}
		if len(existing) > 0 {
			return nil, fmt.Errorf("refusing to overwrite existing files (use -force): %s", strings.Join(existing, ", "))
		}
	}

	if err := os.MkdirAll(abs, 0o755); err != nil {
		return nil, err
	}
	for _, sub := range []string{"data", "mail", "tls", "dkim", filepath.Join("data", "queue"), filepath.Join("data", "quarantine")} {
		if err := os.MkdirAll(filepath.Join(abs, sub), 0o700); err != nil {
			return nil, err
		}
	}

	_, keyPEM, dnsValue, err := dkimkey.GenerateRSA(keyBits)
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(dkimPath, []byte(keyPEM), 0o600); err != nil {
		return nil, fmt.Errorf("write DKIM key: %w", err)
	}
	if err := tlsutil.GenerateSelfSigned(certPath, keyPath, hostname); err != nil {
		return nil, err
	}

	configBody := configTemplate(hostname)
	if err := os.WriteFile(configPath, []byte(configBody), 0o644); err != nil {
		return nil, err
	}
	pluginsBody := pluginsTemplate(domains, selector)
	if err := os.WriteFile(pluginsPath, []byte(pluginsBody), 0o644); err != nil {
		return nil, err
	}
	if err := os.WriteFile(domainsPath, []byte(domainsTemplate(domains)), 0o644); err != nil {
		return nil, err
	}
	usersBody := fmt.Sprintf("# GoMTA users: username:bcrypt-hash\n# Generated by `gomta init`.\n%s:%s\n", adminUser, hash)
	if err := os.WriteFile(usersPath, []byte(usersBody), 0o600); err != nil {
		return nil, err
	}

	var records []DNSRecord
	for _, domain := range domains {
		name := dkimkey.RecordName(selector, domain)
		records = append(records, DNSRecord{
			Name:  name,
			Type:  "TXT",
			Value: dnsValue,
			Note:  "DKIM signing key",
		})
		records = append(records, DNSRecord{
			Name:  domain,
			Type:  "TXT",
			Value: "v=spf1 mx -all",
			Note:  "Suggested SPF policy; adjust to your sending infrastructure",
		})
		records = append(records, DNSRecord{
			Name:  "_dmarc." + domain,
			Type:  "TXT",
			Value: "v=DMARC1; p=none; rua=mailto:" + adminUser,
			Note:  "Suggested DMARC record; move to quarantine/reject after monitoring",
		})
	}
	records = append(records,
		DNSRecord{Name: hostname, Type: "A/AAAA", Value: "<public IP>", Note: "SMTP host address"},
		DNSRecord{Name: hostname, Type: "MX", Value: "10 " + hostname, Note: "Required to receive mail for local domains"},
	)

	res := &Result{
		Dir:               abs,
		ConfigPath:        configPath,
		Hostname:          hostname,
		Domains:           domains,
		AdminUser:         adminUser,
		Password:          password,
		PasswordGenerated: generated,
		Selector:          selector,
		KeyFile:           dkimPath,
		DNSRecords:        records,
		GeneratedFiles:    []string{configPath, pluginsPath, domainsPath, usersPath, dkimPath, certPath, keyPath},
	}
	return res, nil
}

func normalizeDomains(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, raw := range in {
		for _, part := range strings.Split(raw, ",") {
			d := strings.ToLower(strings.TrimSpace(part))
			d = strings.TrimSuffix(d, ".")
			if d == "" || seen[d] {
				continue
			}
			seen[d] = true
			out = append(out, d)
		}
	}
	sort.Strings(out)
	return out
}

func randomPassword() (string, error) {
	buf := make([]byte, 18)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(buf), nil
}

